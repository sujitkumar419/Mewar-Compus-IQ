@app.post("/api/quiz/submit")
@login_required
def submit_quiz():
    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({
            "success": False,
            "error": "Request body must be valid JSON."
        }), 400

    answers = data.get("answers")

    if not isinstance(answers, list) or len(answers) != 3:
        return jsonify({
            "success": False,
            "error": "Please submit exactly 3 quiz answers."
        }), 400

    if any(
        type(answer) is not int or answer not in (0, 1, 2, 3)
        for answer in answers
    ):
        return jsonify({
            "success": False,
            "error": "Each answer must be a valid option index."
        }), 400

    correct_answers = [1, 0, 2]
    score = sum(
        submitted == correct
        for submitted, correct in zip(answers, correct_answers)
    )

    return jsonify({
        "success": True,
        "score": score,
        "total": len(correct_answers),
        "percentage": round(score / len(correct_answers) * 100, 2)
    }), 200


